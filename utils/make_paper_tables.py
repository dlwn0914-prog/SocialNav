#!/usr/bin/env python
"""LaTeX tables for paper/ from the result JSONs, so every number in the
manuscript can be regenerated:
  tables/regret.tex      simple regret, Random / AQ / information gain / EUBO /
                         DPO / DPO+EUBO questions / references
                         (results/codebook/infogain/; same runs as dpo/ plus InfoGain)
  tables/agreement.tex   held-out pairwise agreement, same runs (appendix)
  tables/generator.tex   Crowd-FM vs VQ-VAE x Random / AQ / EUBO, union
                         regret (results/codebook/generator/)
  tables/robust.tex      users the estimator does not describe: answer noise,
                         random answers, nonlinear utility (results/codebook/robust/)
  tables/closed_loop.tex closed-loop replay, final planner (slow/stop
                         candidates + safety-checked goal approach)
                         (results/codebook/closed_loop/*_safe_c0.5.json)
Paired differences: mean and 95% bootstrap CI over users (closed loop:
episodes; ETH closed loop: people), dagger if the CI excludes 0.

Usage:
    PYTHONPATH=. .venv/bin/python utils/make_paper_tables.py --out-dir paper/tables
"""
import argparse
import json
import os

import numpy as np

SETTINGS = [("gc_gauss", "GC", "dense"), ("gc_sparse", "GC", "sparse"),
            ("eth_gauss", "ETH/UCY", "dense"), ("eth_sparse", "ETH/UCY", "sparse")]
METHODS = [("Random", "BT + random queries"), ("ActiveQuery", "BT + active query (AQ)"),
           ("InfoGain", "BT + information gain"), ("DPO", "DPO + random queries"), ("DPO-EUBO", "DPO + EUBO queries"), ("EUBO", "BT + EUBO (ours)")]
COL = {"agreement": 0, "answer_acc": 1, "regret": 2}


def boot(x, rng, n=2000):
    x = np.asarray(x, float)
    m = x[rng.integers(0, len(x), (n, len(x)))].mean(1)
    return float(x.mean()), float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5))


def diff_cell(v):
    m, lo, hi = (0.0 if abs(x) < 5e-4 else x for x in v)  # no "-0.000"
    dag = "$^\\dagger$" if lo > 0 or hi < 0 else ""
    f = lambda x: f"{x:+.3f}".replace("-", "$-$")
    return f"{f(m)}{dag} \\scriptsize{{[{f(lo)}, {f(hi)}]}}"


def benchmark_table(res, metric, rng, lower_better):
    best = min if lower_better else max
    head = ("\\begin{tabular}{lcccc}\n\\toprule\n & \\multicolumn{2}{c}{Grand Central} & \\multicolumn{2}{c}{ETH/UCY} \\\\\n"
            "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\nMethod & dense $\\theta^*$ & sparse $\\theta^*$ & dense $\\theta^*$ & sparse $\\theta^*$ \\\\\n\\midrule\n")
    lines = []
    refs = [("no preference (random safe code)", "Random safe candidate"), ("human prior (argmax log p)", "Human prior only")]
    for key, label in refs:
        lines.append(label + " & " + " & ".join(f"{res[s]['rows'][key][metric][0]:.3f}" for s, _, _ in SETTINGS) + " \\\\")
    lines.append("\\midrule")
    for m, label in METHODS:
        cells = []
        for s, _, _ in SETTINGS:
            c = res[s]["curves"]
            v5, v20 = c[m]["5"][metric][0], c[m]["20"][metric][0]
            top = best(c[k]["5"][metric][0] for k, _ in METHODS)
            cell = f"{v5:.3f}"
            cells.append(("\\textbf{" + cell + "}" if v5 == top else cell) + f" \\scriptsize{{({v20:.3f})}}")
        lines.append(label + " & " + " & ".join(cells) + " \\\\")
    lines.append("Oracle $\\theta^*$ & " + " & ".join(f"{res[s]['rows']['oracle theta*'][metric][0]:.3f}" for s, _, _ in SETTINGS) + " \\\\")
    lines.append("\\midrule")
    for other, label in [("Random", "EUBO $-$ Random"), ("ActiveQuery", "EUBO $-$ AQ"), ("InfoGain", "EUBO $-$ InfoGain"),
                         ("DPO", "EUBO $-$ DPO")]:
        cells = []
        for s, _, _ in SETTINGS:
            P = res[s]["per_user"]
            d = np.array(P["EUBO"]["5"])[:, COL[metric]] - np.array(P[other]["5"])[:, COL[metric]]
            cells.append(diff_cell(boot(d, rng)))
        lines.append(label + " (5 q) & " + " & ".join(cells) + " \\\\")
    return head + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n"


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--dpo-dir", default="results/codebook/infogain")
    p.add_argument("--robust-dir", default="results/codebook/robust")
    p.add_argument("--gen-dir", default="results/codebook/generator")
    p.add_argument("--cl-dir", default="results/codebook/closed_loop")
    p.add_argument("--out-dir", default="paper/tables")
    p.add_argument("--seed", type=int, default=0)
    args = p.parse_args()
    rng = np.random.default_rng(args.seed)
    os.makedirs(args.out_dir, exist_ok=True)
    src = lambda files: "% Generated by utils/make_paper_tables.py from " + files + "\n"

    res = {s: json.load(open(f"{args.dpo_dir}/{s}.json")) for s, _, _ in SETTINGS}
    n_users = res["gc_gauss"]["args"]["n_users"]
    open(f"{args.out_dir}/regret.tex", "w").write(
        src(f"{args.dpo_dir}/{{gc,eth}}_{{gauss,sparse}}.json") +
        "\\begin{table}[t]\n\\centering\n\\caption{Simple regret $\\mathrm{SR}_n$ (Eq.~\\ref{eq:sr}, lower is better) on held-out situations "
        f"after 5 queries (20 in parentheses). Synthetic users ({n_users} per setting); paired differences after 5 queries with 95\\% "
        "bootstrap CI over users; $^\\dagger$: CI excludes 0. BT: Bayesian Bradley--Terry (Laplace).}\n\\label{tab:regret}\n"
        "\\setlength{\\tabcolsep}{3pt}\n\\resizebox{\\linewidth}{!}{%\n" + benchmark_table(res, "regret", rng, True) + "}\n\\end{table}\n")
    open(f"{args.out_dir}/agreement.tex", "w").write(
        src(f"{args.dpo_dir}/{{gc,eth}}_{{gauss,sparse}}.json") +
        "\\begin{table}[h]\n\\centering\n\\caption{Held-out pairwise agreement with the user's preference (higher is better) after 5 queries "
        "(20 in parentheses); same runs as Table~\\ref{tab:regret}.}\n\\label{tab:agreement}\n\\setlength{\\tabcolsep}{3pt}\n"
        "\\resizebox{\\linewidth}{!}{%\n" + benchmark_table(res, "agreement", rng, False) + "}\n\\end{table}\n")

    # robustness: users outside the estimator's model (dense users)
    CONDS = [("b1", "answer noise $\\beta=1$"), ("b2", "answer noise $\\beta=2$"), ("b10", "answer noise $\\beta=10$"),
             ("lapse20", "20\\% random answers"), ("nl05", "nonlinear utility, $w=0.5$"), ("nl10", "nonlinear utility, $w=1$")]
    RM = [("Random", "Random"), ("ActiveQuery", "AQ"), ("DPO", "DPO"), ("InfoGain", "InfoGain"), ("EUBO", "EUBO")]
    lines = []
    for ds, name in [("gc", "Grand Central"), ("eth", "ETH/UCY")]:
        lines.append(f"\\multicolumn{{8}}{{l}}{{\\emph{{{name}}}}} \\\\")
        for c, label in CONDS:
            r = json.load(open(f"{args.robust_dir}/{ds}_{c}.json"))
            v = {m: r["curves"][m]["5"]["regret"][0] for m, _ in RM}
            top = min(v.values())
            cells = [f"{r['rows']['human prior (argmax log p)']['regret'][0]:.3f}"]
            for m, _ in RM:
                cell = f"{v[m]:.3f}"
                if m == "EUBO" and all(r["paired"][f"EUBO - {o}"]["5"]["regret"][2] < 0 for o in ("Random", "ActiveQuery", "DPO")):
                    cell += "$^\\dagger$"
                cells.append("\\textbf{" + cell + "}" if v[m] == top else cell)
            cells.append(f"{r['rows']['oracle theta*']['regret'][0]:.3f}")
            lines.append(label + " & " + " & ".join(cells) + " \\\\")
        lines.append("\\midrule" if ds == "gc" else "")
    open(f"{args.out_dir}/robust.tex", "w").write(
        src(f"{args.robust_dir}/{{gc,eth}}_*.json") +
        "\\begin{table}[h]\n\\centering\n\\caption{Simple regret after 5 queries for users the estimator does not describe (dense "
        "$\\theta^*$, 200 users each; the main experiments use $\\beta=5$ and linear utilities). $\\beta$: answer noise (lower is noisier); "
        "random answers: each answer is a coin flip with probability 0.2; nonlinear: pairwise feature interactions with weight $w$ added to "
        "the true utility, so the oracle $\\theta^*$ no longer reaches 0. $^\\dagger$: EUBO's 95\\% CI over users is below Random, AQ and DPO.}\n"
        "\\label{tab:robust}\n\\setlength{\\tabcolsep}{3pt}\n\\resizebox{\\linewidth}{!}{%\n"
        "\\begin{tabular}{lccccccc}\n\\toprule\nUsers & Prior & Random & AQ & DPO & InfoGain & EUBO & Oracle $\\theta^*$ \\\\\n\\midrule\n"
        + "\n".join(l for l in lines if l) + "\n\\bottomrule\n\\end{tabular}\n}\n\\end{table}\n")

    # candidate generators
    G = {u: json.load(open(f"{args.gen_dir}/gc_{u}.json")) for u in ("gauss", "sparse")}
    rows = []
    for gen in ("Crowd-FM", "VQ-VAE"):
        for m, label in [("Random", "random queries"), ("ActiveQuery", "AQ"), ("EUBO", "EUBO")]:
            name = f"{gen}+{m}"
            cells = []
            for u in ("gauss", "sparse"):
                c = G[u]["curves"][name]
                cells.append(f"{c['5']['union_regret'][0]:.3f} \\scriptsize{{({c['20']['union_regret'][0]:.3f})}} & "
                             f"{c['5']['own_regret'][0]:.3f}")
            lab = f"{gen} + {label}" + (" (ours)" if name == "VQ-VAE+EUBO" else "")
            rows.append(lab + " & " + " & ".join(cells) + " \\\\")
        cells = [f"{G[u]['summary'][f'{gen} oracle']['union_regret'][0]:.3f} & 0" for u in ("gauss", "sparse")]
        rows.append(f"{gen} oracle $\\theta^*$ & " + " & ".join(cells) + " \\\\")
        rows.append("\\midrule")
    for a, b, label in [("VQ-VAE+EUBO", "Crowd-FM+EUBO", "VQ-VAE+EUBO $-$ Crowd-FM+EUBO"),
                        ("Crowd-FM+EUBO", "Crowd-FM+Random", "Crowd-FM: EUBO $-$ random"),
                        ("VQ-VAE+EUBO", "VQ-VAE+Random", "VQ-VAE: EUBO $-$ random")]:
        cells = [diff_cell(G[u]["paired"][f"{a} - {b}"]["5"]["union_regret"]) + " & " for u in ("gauss", "sparse")]
        rows.append(label + " (5 q) & " + " & ".join(cells) + " \\\\")
    g = G["gauss"]
    open(f"{args.out_dir}/generator.tex", "w").write(
        src(f"{args.gen_dir}/gc_{{gauss,sparse}}.json") +
        "\\begin{table}[t]\n\\centering\n\\caption{Candidate generator $\\times$ query method on the same "
        f"{g['n_ok']} Grand Central scenes (first 3\\,s, four style features without \\emph{{human}}). Union regret: Eq.~\\ref{{eq:regret}} "
        "normalized over the safe candidates of both generators (comparable across generators); own regret: within the generator's "
        "own candidates (not comparable). 5 queries (20 in parentheses), "
        f"{g['args']['n_users']} synthetic users.}}\n\\label{{tab:generator}}\n\\setlength{{\\tabcolsep}}{{3pt}}\n\\resizebox{{\\linewidth}}{{!}}{{%\n"
        "\\begin{tabular}{lcccc}\n\\toprule\n & \\multicolumn{2}{c}{dense $\\theta^*$} & \\multicolumn{2}{c}{sparse $\\theta^*$} \\\\\n"
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\nCandidates + queries & union regret & own regret & union regret & own regret \\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}}\n\\end{table}\n")

    # closed loop
    CL = {f"{ds}_{u}": json.load(open(f"{args.cl_dir}/{ds}_{u}_safe_c0.5.json")) for ds in ("gc", "eth") for u in ("gauss", "sparse")}
    M = [("reached", "reached"), ("collision", "collision"), ("coll_robot", "robot-caused"), ("regret", "step regret")]
    rows = []
    for key, label in [("gc_gauss", "GC, dense"), ("gc_sparse", "GC, sparse"), ("eth_gauss", "ETH/UCY, dense"), ("eth_sparse", "ETH/UCY, sparse")]:
        j = CL[key]
        for r, name in [("human", "recorded pedestrian"), ("prior", "human prior"), ("pref-5q", "preference, 5 q"),
                        ("pref-20q", "preference, 20 q"), ("oracle", "oracle $\\theta^*$")]:
            if r == "human" and key.endswith("sparse"):
                continue
            cells = [f"{j['rows'][r][m][0] + 0.0:.3f}".replace("-0.000", "0.000") if j["rows"][r][m] else "--" for m, _ in M]
            rows.append(f"{label if r in ('human', 'prior') and (r == 'human' or key.endswith('sparse')) else ''} & {name} & " + " & ".join(cells) + " \\\\")
        d = j["paired"]["pref-5q - prior"]
        rows.append(" & 5 q $-$ prior & " + " & ".join(diff_cell(d[m]) for m, _ in M) + " \\\\")
        rows.append("\\midrule")
    rows[-1] = "\\bottomrule"
    eg, ee = CL["gc_gauss"], CL["eth_gauss"]
    open(f"{args.out_dir}/closed_loop.tex", "w").write(
        src(f"{args.cl_dir}/{{gc,eth}}_{{gauss,sparse}}_safe_c0.5.json") +
        "\\begin{table}[t]\n\\centering\n\\caption{Closed-loop replay (non-reactive pedestrians, re-planning every 0.8\\,s, clearance 0.5\\,m, "
        f"collision $<$ 0.4\\,m). GC: {eg['n_episodes']} episodes; ETH/UCY: {ee['n_episodes']} episodes from {ee.get('n_people')} people. "
        "Robot-caused: the robot's own motion closes the gap faster than the person's at the closest moment. Paired differences with 95\\% "
        "bootstrap CI.}\n\\label{tab:closed_loop}\n\\setlength{\\tabcolsep}{3pt}\n\\resizebox{\\linewidth}{!}{%\n"
        "\\begin{tabular}{llcccc}\n\\toprule\nSetting & Policy & " + " & ".join(l for _, l in M) + " \\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\end{tabular}}\n\\end{table}\n")
    print(f"wrote {args.out_dir}/{{regret,agreement,generator,closed_loop}}.tex")


if __name__ == "__main__":
    main()
